using Majorsilence.Sql2Postgre.Postgres;
using Majorsilence.Sql2Postgre.Translation.Names;
using Majorsilence.Sql2Postgre.Translation.PgAst;

namespace Majorsilence.Sql2Postgre.Tests.Postgres;

public class PgWriterDdlTests
{
    private static readonly PgName Orders = new("sales", "order");
    private static readonly PgName Customer = new("sales", "customer");

    private static string W(PgStatement s, int version = 17) => PgWriter.Write(s, version);

    [Test]
    public void Schema() => Assert.That(W(new PgCreateSchema("Sales")), Is.EqualTo("CREATE SCHEMA IF NOT EXISTS \"Sales\";\n"));

    [Test]
    public void Extension() => Assert.That(W(new PgCreateExtension("uuid-ossp")), Is.EqualTo("CREATE EXTENSION IF NOT EXISTS \"uuid-ossp\";\n"));

    [Test]
    public void Collation() => Assert.That(W(new PgCreateCollation(new PgName("public", "sql2pg_ci"), "icu", "und-u-ks-level2", false)),
        Is.EqualTo("CREATE COLLATION IF NOT EXISTS public.sql2pg_ci (provider = icu, locale = 'und-u-ks-level2', deterministic = false);\n"));

    [Test]
    public void Domain()
    {
        Assert.That(W(new PgCreateDomain(new PgName("shop", "phone"), "varchar(20)", false)), Is.EqualTo("CREATE DOMAIN shop.phone AS varchar(20);\n"));
        Assert.That(W(new PgCreateDomain(new PgName("shop", "code"), "char(3)", true)), Is.EqualTo("CREATE DOMAIN shop.code AS char(3) NOT NULL;\n"));
    }

    [Test]
    public void CompositeType() =>
        Assert.That(W(new PgCreateCompositeType(new PgName("shop", "line_list"), [new("product_id", "integer"), new("user", "integer")])),
            Is.EqualTo("CREATE TYPE shop.line_list AS (\n    product_id integer,\n    \"user\" integer\n);\n"));

    [Test]
    public void Sequence()
    {
        Assert.That(W(new PgCreateSequence(new PgName("shop", "invoice_no"), "bigint", 1000, 10, 1000, 999999, false)),
            Is.EqualTo("CREATE SEQUENCE shop.invoice_no AS bigint START WITH 1000 INCREMENT BY 10 MINVALUE 1000 MAXVALUE 999999 NO CYCLE;\n"));
        Assert.That(W(new PgCreateSequence(new PgName("shop", "s"), "integer", -1, -1, null, null, true)),
            Is.EqualTo("CREATE SEQUENCE shop.s AS integer START WITH -1 INCREMENT BY -1 NO MINVALUE NO MAXVALUE CYCLE;\n"));
    }

    [Test]
    public void TableWithEveryColumnFeature()
    {
        var table = new PgCreateTable(Orders, [
            new("order_id", "bigint", NotNull: true, Identity: new PgIdentity(100, 5)),
            new("name", "varchar(100)", NotNull: true, Collation: "public.sql2pg_ci"),
            new("is_active", "boolean", NotNull: true, Default: PgLiteral.True),
            new("total", "numeric(12,2)", Generated: new PgGenerated(new PgBinary("*", new PgColumnRef("qty"), new PgColumnRef("price")), Stored: true)),
            new("user", "text"),
        ]);
        Assert.That(W(table), Is.EqualTo("""
            CREATE TABLE sales."order" (
                order_id bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 100 INCREMENT BY 5) NOT NULL,
                name varchar(100) COLLATE public.sql2pg_ci NOT NULL,
                is_active boolean DEFAULT true NOT NULL,
                total numeric(12,2) GENERATED ALWAYS AS (qty * price) STORED,
                "user" text
            );

            """.Replace("\r\n", "\n")));
    }

    [TestCase(17, "STORED")]
    [TestCase(18, "VIRTUAL")]
    public void VirtualGeneratedColumnsNeedEighteen(int version, string expected)
    {
        var table = new PgCreateTable(Orders, [new("tax", "numeric", Generated: new PgGenerated(new PgColumnRef("x"), Stored: false))]);
        Assert.That(W(table, version), Does.Contain($"GENERATED ALWAYS AS (x) {expected}"));
    }

    [Test]
    public void TableCarriesUntranslatedComments()
    {
        var table = new PgCreateTable(Orders, [new("a", "integer")]) { Comments = [new PgUntranslated("S2P3001", "DEFAULT (dbo.f())")] };
        Assert.That(W(table), Is.EqualTo("CREATE TABLE sales.\"order\" (\n    a integer\n    /* sql2pg:untranslated S2P3001\n    DEFAULT (dbo.f())\n    */\n);\n"));
    }

    [Test]
    public void Constraints()
    {
        Assert.Multiple(() =>
        {
            Assert.That(W(new PgAddPrimaryKey(Orders, "order_pkey", ["order_id", "line"])),
                Is.EqualTo("ALTER TABLE sales.\"order\" ADD CONSTRAINT order_pkey PRIMARY KEY (order_id, line);\n"));
            Assert.That(W(new PgAddUnique(Customer, "uq_code", ["code"])),
                Is.EqualTo("ALTER TABLE sales.customer ADD CONSTRAINT uq_code UNIQUE (code);\n"));
            Assert.That(W(new PgAddCheck(Customer, "ck_qty", new PgBinary(">", new PgColumnRef("qty"), new PgLiteral("0")), NotValid: true)),
                Is.EqualTo("ALTER TABLE sales.customer ADD CONSTRAINT ck_qty CHECK (qty > 0) NOT VALID;\n"));
        });
    }

    [Test]
    public void ForeignKeys()
    {
        Assert.That(W(new PgAddForeignKey(Orders, "fk", ["customer_id"], Customer, ["customer_id"], "CASCADE", "SET NULL", NotValid: true)),
            Is.EqualTo("ALTER TABLE sales.\"order\" ADD CONSTRAINT fk FOREIGN KEY (customer_id) REFERENCES sales.customer (customer_id) ON DELETE CASCADE ON UPDATE SET NULL NOT VALID;\n"));
        Assert.That(W(new PgAddForeignKey(Orders, "fk", ["a"], Customer, ["b"])),
            Is.EqualTo("ALTER TABLE sales.\"order\" ADD CONSTRAINT fk FOREIGN KEY (a) REFERENCES sales.customer (b);\n"));
    }

    [Test]
    public void Indexes()
    {
        Assert.Multiple(() =>
        {
            Assert.That(W(new PgCreateIndex("ix", Customer, [new("email", Descending: true)], ["name"], Unique: true,
                    Where: new PgBinary("=", new PgColumnRef("is_active"), PgLiteral.True))),
                Is.EqualTo("CREATE UNIQUE INDEX ix ON sales.customer (email DESC) INCLUDE (name) WHERE is_active = true;\n"));
            Assert.That(W(new PgCreateIndex("ix_geo", Customer, [new("location")], [], Method: "gist")),
                Is.EqualTo("CREATE INDEX ix_geo ON sales.customer USING gist (location);\n"));
        });
    }

    [Test]
    public void UntranslatedCannotCloseItsCommentEarly() =>
        Assert.That(W(new PgUntranslated("S2P3001", "SELECT 1 /* inner */ AS x")),
            Is.EqualTo("/* sql2pg:untranslated S2P3001\nSELECT 1 / * inner * / AS x\n*/\n"));

    [Test]
    public void LineComment() => Assert.That(W(new PgLineComment("first\nsecond")), Is.EqualTo("-- first\n-- second\n"));
}
