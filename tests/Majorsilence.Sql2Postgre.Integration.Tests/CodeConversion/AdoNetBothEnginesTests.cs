using Majorsilence.Sql2Postgre.CodeConversion;
using Majorsilence.Sql2Postgre.Integration.Tests.Infrastructure;
using Majorsilence.Sql2Postgre.Model;
using Npgsql;

namespace Majorsilence.Sql2Postgre.Integration.Tests.CodeConversion;

/// <summary>
/// An ADO.NET program, in C# and in VB.NET, converted by <c>sql2pg code</c>: before conversion it
/// runs on SQL Server, after it on PostgreSQL, and it prints the same. It covers parameters with
/// SqlDbType, a unique violation caught by error number, a transaction and a data reader. (Its
/// SQL is written to run on both engines; translating SQL in code is WP A.3.)
/// </summary>
[Category("Containers")]
public class AdoNetBothEnginesTests
{
    private const string SqlServerSchema = """
        CREATE TABLE dbo.item (id int IDENTITY NOT NULL PRIMARY KEY, name nvarchar(50) NOT NULL UNIQUE, price decimal(10, 2) NOT NULL);
        GO
        INSERT INTO dbo.item (name, price) VALUES (N'apple', 1.20), (N'banana', 0.80), (N'cheese', 12.00);
        GO
        """;

    private const string PostgresSchema = """
        CREATE TABLE public.item (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name varchar(50) NOT NULL UNIQUE, price numeric(10,2) NOT NULL);
        INSERT INTO public.item (name, price) VALUES ('apple', 1.20), ('banana', 0.80), ('cheese', 12.00);
        """;

    private const string CSharp = """
        using System;
        using System.Data;
        using System.Globalization;
        using System.Text;
        using Microsoft.Data.SqlClient;

        public static class Sample
        {
            public static string Run(string connectionString)
            {
                var output = new StringBuilder();
                using (var connection = new SqlConnection(connectionString))
                {
                    connection.Open();
                    using (SqlTransaction transaction = connection.BeginTransaction())
                    {
                        using var insert = new SqlCommand("INSERT INTO item (name, price) VALUES (@name, @price)", connection, transaction);
                        insert.Parameters.Add(new SqlParameter("@name", SqlDbType.NVarChar, 50) { Value = "kiwi" });
                        var price = insert.Parameters.Add("@price", SqlDbType.Decimal);
                        price.Value = 2.50m;
                        output.Append("inserted ").Append(insert.ExecuteNonQuery()).Append(';');
                        transaction.Commit();
                    }
                    try
                    {
                        using var duplicate = new SqlCommand("INSERT INTO item (name, price) VALUES (@name, 1)", connection);
                        duplicate.Parameters.AddWithValue("@name", "kiwi");
                        duplicate.ExecuteNonQuery();
                        output.Append("no error;");
                    }
                    catch (SqlException ex) when (ex.Number == 2627 || ex.Number == 2601)
                    {
                        output.Append("duplicate;");
                    }
                    using (var select = new SqlCommand("SELECT name, price FROM item WHERE price < @max ORDER BY name", connection))
                    {
                        select.Parameters.Add("@max", SqlDbType.Decimal).Value = 5m;
                        using SqlDataReader reader = select.ExecuteReader();
                        while (reader.Read())
                            output.Append(reader.GetString(0)).Append('=').Append(reader.GetDecimal(1).ToString("0.00", CultureInfo.InvariantCulture)).Append(';');
                    }
                }
                return output.ToString();
            }
        }
        """;

    private const string VisualBasic = """
        Imports System.Data
        Imports System.Globalization
        Imports System.Text
        Imports Microsoft.Data.SqlClient

        Public Module Sample
            Public Function Run(connectionString As String) As String
                Dim output As New StringBuilder()
                Using connection As New SqlConnection(connectionString)
                    connection.Open()
                    Using insert As New SqlCommand("INSERT INTO item (name, price) VALUES (@name, @price)", connection)
                        insert.Parameters.Add(New SqlParameter("@name", SqlDbType.NVarChar, 50) With {.Value = "kiwi"})
                        insert.Parameters.Add("@price", SqlDbType.Decimal).Value = 2.5D
                        output.Append("inserted ").Append(insert.ExecuteNonQuery()).Append(";"c)
                    End Using
                    Try
                        Using duplicate As New SqlCommand("INSERT INTO item (name, price) VALUES (@name, 1)", connection)
                            duplicate.Parameters.AddWithValue("@name", "kiwi")
                            duplicate.ExecuteNonQuery()
                            output.Append("no error;")
                        End Using
                    Catch ex As SqlException When ex.Number = 2627 OrElse ex.Number = 2601
                        output.Append("duplicate;")
                    End Try
                    Using query As New SqlCommand("SELECT name, price FROM item WHERE price < @max ORDER BY name", connection)
                        query.Parameters.Add("@max", SqlDbType.Decimal).Value = 5D
                        Using reader As SqlDataReader = query.ExecuteReader()
                            While reader.Read()
                                output.Append(reader.GetString(0)).Append("="c).Append(reader.GetDecimal(1).ToString("0.00", CultureInfo.InvariantCulture)).Append(";"c)
                            End While
                        End Using
                    End Using
                End Using
                Return output.ToString()
            End Function
        End Module
        """;

    [TestCase(CSharp, "Sample.cs")]
    [TestCase(VisualBasic, "Sample.vb")]
    public async Task SameOutputAfterConversion(string source, string file)
    {
        var converted = new CodeConverter(new CodeConversionOptions(new ConversionOptions { TargetVersion = Engines.TargetVersion })).ConvertFile(file, source);
        Assert.That(converted.Diagnostics.Where(d => d.Severity == Severity.Error), Is.Empty);
        Assert.That(converted.NewText, Does.Not.Contain("SqlClient").And.Not.Contain("SqlDbType."), converted.NewText);

        await using var sqlServer = await SqlServerDatabase.CreateAsync(SqlServerSchema, "adonet");
        await using var postgres = await PostgresDatabase.CreateAsync("adonet");
        await using (var conn = new NpgsqlConnection(postgres.ConnectionString))
        {
            await conn.OpenAsync();
            await using var setup = new NpgsqlCommand(PostgresSchema, conn);
            await setup.ExecuteNonQueryAsync();
        }

        string language = file.EndsWith(".vb", StringComparison.Ordinal) ? "VB" : "C#";
        string before = SampleProgram.Run(source, language, sqlServer.ConnectionString);
        string after = SampleProgram.Run(converted.NewText, language, postgres.ConnectionString);
        Assert.Multiple(() =>
        {
            Assert.That(before, Is.EqualTo("inserted 1;duplicate;apple=1.20;banana=0.80;kiwi=2.50;"));
            Assert.That(after, Is.EqualTo(before), converted.NewText);
        });
    }
}
