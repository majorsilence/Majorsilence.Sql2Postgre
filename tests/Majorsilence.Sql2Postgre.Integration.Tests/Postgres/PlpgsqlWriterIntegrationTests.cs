using System.Globalization;
using Majorsilence.Sql2Postgre.Integration.Tests.Infrastructure;
using Majorsilence.Sql2Postgre.Postgres;
using Majorsilence.Sql2Postgre.Translation.Names;
using Majorsilence.Sql2Postgre.Translation.PgAst;
using Npgsql;

namespace Majorsilence.Sql2Postgre.Integration.Tests.Postgres;

/// <summary>
/// Routines built from every PL/pgSQL node are created and run on PostgreSQL: the writer's output
/// must compile, and the control flow it describes must compute what the tree says.
/// </summary>
[Category("Containers")]
public class PlpgsqlWriterIntegrationTests
{
    private static readonly PgName Item = new("plpg", "item");

    private const string Setup = """
        CREATE SCHEMA plpg;
        CREATE TABLE plpg.item (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, qty integer NOT NULL, note text);
        INSERT INTO plpg.item (qty) SELECT g * 10 FROM generate_series(1, 5) AS g;
        """;

    private static PgColumnRef V(string name, string? qualifier = null) => new(name, qualifier);

    private static PgLiteral N(int n) => new(n.ToString(CultureInfo.InvariantCulture));

    private static PgBinary Add(PgExpr a, PgExpr b) => new("+", a, b);

    private static PgAssign AddTo(string variable, PgExpr value) => new(V(variable), Add(V(variable), value));

    private static PgSelect QtyWhere(PgExpr where, bool orderById = false) => new()
    {
        Targets = [new PgTarget(V("qty"))],
        From = [new PgTableRef(Item)],
        Where = where,
        OrderBy = orderById ? [new PgSortKey(V("id"))] : [],
    };

    private static async Task<NpgsqlConnection> OpenAsync(PostgresDatabase db, params PgStatement[] routines)
    {
        var conn = new NpgsqlConnection(db.ConnectionString);
        await conn.OpenAsync();
        await using (var setup = new NpgsqlCommand(Setup, conn))
            await setup.ExecuteNonQueryAsync();
        foreach (var routine in routines)
        {
            string sql = PgWriter.Write(routine, 18);
            await using var create = new NpgsqlCommand(sql, conn);
            try
            {
                await create.ExecuteNonQueryAsync();
            }
            catch (PostgresException ex)
            {
                Assert.Fail($"{ex.MessageText}\n\n{sql}");
            }
        }
        return conn;
    }

    private static async Task<object?> ScalarAsync(NpgsqlConnection conn, string sql)
    {
        await using var cmd = new NpgsqlCommand(sql, conn);
        return await cmd.ExecuteScalarAsync();
    }

    [Test]
    public async Task EveryStatementKindRunsAndComputes()
    {
        var item = new PgTableRef(Item);
        var nested = new PgBlock([
            new PgBlock([new PgRaise("EXCEPTION", "custom %") { Arguments = [N(7)], Using = [new("ERRCODE", PgLiteral.String("P0001"))] }])
            {
                Handlers = [new PgExceptionHandler(["OTHERS"], [PgRaise.Rethrow])],
            },
        ])
        {
            Handlers = [new PgExceptionHandler(["SQLSTATE 'P0001'"], [
                new PgGetDiagnostics([new("v_msg", "MESSAGE_TEXT")], Stacked: true),
                new PgIf([new PgIfBranch(new PgBinary("=", V("v_msg"), PgLiteral.String("custom 7")), [AddTo("v_total", N(100))])]),
            ])],
        };
        var body = new PgBlock([
            new PgWhile(new PgBinary("<", V("v_i"), N(100)), [
                AddTo("v_i", N(1)),
                new PgContinue(When: new PgBinary("=", new PgBinary("%", V("v_i"), N(2)), N(0))),
                AddTo("v_total", V("v_i")),
                new PgExit("w", new PgBinary(">=", V("v_i"), N(9))),
            ], "w"),                                                                                     // 1+3+5+7+9 = 25
            new PgForRange("i", N(10), N(1), [AddTo("v_total", V("i"))]) { Reverse = true, Step = N(3) }, // +10+7+4+1 = 47
            new PgLoop([new PgExit()]),
            new PgForQuery("r", QtyWhere(new PgBinary("<=", V("id"), V("n", "exercise"))), [AddTo("v_total", V("qty", "r"))]), // +60 = 107
            new PgForQuery("r", null, [AddTo("v_total", V("qty", "r"))])
            {
                Execute = PgLiteral.String("SELECT qty FROM plpg.item WHERE id = $1"),
                Using = [N(5)],
            },                                                                                           // +50 = 157
            new PgIf([
                new PgIfBranch(new PgBinary(">", V("v_total"), N(1000)), [new PgReturn(N(-1))]),
                new PgIfBranch(new PgBinary("=", V("v_total"), N(157)), [AddTo("v_total", N(1))]),
            ], [new PgReturn(N(-2))]),                                                                   // 158
            new PgOpenCursor("c") { Arguments = [N(2)] },
            new PgFetch("c", [V("v_qty")]),
            new PgFetch("c", [V("v_qty")]),
            new PgClose("c"),
            AddTo("v_total", V("v_qty")),                                                                // +20 = 178
            new PgOpenCursor("sc"),
            new PgFetch("sc", [], "ABSOLUTE") { Count = N(5), Move = true },
            new PgFetch("sc", [V("v_qty")], "PRIOR"),
            new PgClose("sc"),
            AddTo("v_total", V("v_qty")),                                                                // +40 = 218
            new PgOpenCursor("rc") { Query = new PgSelect { Targets = [new PgTarget(new PgCast(new PgFunctionCall("count", []) { Star = true }, "integer"))], From = [item] } },
            new PgFetch("rc", [V("v_rows")]),
            new PgClose("rc"),
            AddTo("v_total", V("v_rows")),                                                               // +5 = 223
            new PgOpenCursor("rc") { Execute = PgLiteral.String("SELECT $1 * 2"), Using = [N(3)], Scroll = false },
            new PgFetch("rc", [V("v_rows")]),
            new PgClose("rc"),
            AddTo("v_total", V("v_rows")),                                                               // +6 = 229
            new PgPerform(new PgSelect { Targets = [new PgTarget(new PgFunctionCall("pg_sleep", [N(0)]))], From = [item], Where = new PgBinary("=", V("id"), N(1)) }),
            new PgPerform(new PgSetOperation("UNION ALL", new PgSelect { Targets = [new PgTarget(N(1))] }, new PgSelect { Targets = [new PgTarget(N(2))] })),
            new PgExecuteDynamic(new PgFunctionCall("format", [PgLiteral.String("SELECT sum(qty)::integer FROM %I.%I WHERE id > $1"), PgLiteral.String("plpg"), PgLiteral.String("item")]))
            {
                Into = [V("v_rows")],
                Strict = true,
                Using = [N(3)],
            },
            AddTo("v_total", V("v_rows")),                                                               // +90 = 319
            new PgSqlStatement(new PgUpdate(Item, null, [new PgAssignment("note", V("v_note"))]) { Where = new PgBinary("<=", V("id"), N(2)) }),
            new PgGetDiagnostics([new("v_rows", "ROW_COUNT")]),
            AddTo("v_total", V("v_rows")),                                                               // +2 = 321
            new PgSqlStatement(new PgQueryStatement(new PgSelect
            {
                Targets = [new PgTarget(V("qty")), new PgTarget(V("id"))],
                From = [item],
                Where = new PgBinary("=", V("id"), N(4)),
            }))
            { Into = [V("v_qty"), V("v_id")] },
            AddTo("v_total", V("v_qty")),                                                                // +40 = 361
            new PgSqlStatement(new PgInsert(Item, ["qty"], new PgValues([[N(0)]])) { Returning = [new PgTarget(V("id"))] }) { Into = [V("v_id")], Strict = true },
            AddTo("v_total", V("v_id")),                                                                 // +6 = 367
            new PgBlock([new PgAssign(V("v_rows"), new PgBinary("/", N(1), N(0)))])
            {
                Handlers = [new PgExceptionHandler(["division_by_zero"], [
                    new PgGetDiagnostics([new("v_msg", "MESSAGE_TEXT")], Stacked: true),
                    AddTo("v_total", new PgFunctionCall("length", [V("v_msg")])),                       // "division by zero": +16 = 383
                ])],
            },
            nested,                                                                                      // +100 = 483
            new PgRaise("NOTICE", "total %") { Arguments = [V("v_total")] },
            new PgAssert(new PgBinary(">", V("v_total"), N(0)), PgLiteral.String("positive")),
            PgNullStatement.Instance,
            new PgSqlStatement(new PgUntranslated("S2P9001", "PRINT '$$ /* not closed'")),
            new PgSqlStatement(new PgLineComment("a note; it's fine")),
            new PgIf([new PgIfBranch(new PgBinary("=", new PgFunctionCall("length", [V("v_note")]), N(3)), [AddTo("v_total", N(1))])]), // +1 = 484
            new PgReturn(V("v_total")),
        ])
        {
            Label = "main_block",
            Declarations = [
                new PgDeclare("v_total", "integer", N(0)),
                new PgDeclare("v_i", "integer", N(0), NotNull: true),
                new PgDeclare("v_qty", "integer"),
                new PgDeclare("v_id", "integer"),
                new PgDeclare("v_rows", "integer"),
                new PgDeclare("v_msg", "text"),
                new PgDeclare("v_note", "text", PgLiteral.String("a\nb"), Constant: true),
                new PgDeclareCursor("c", QtyWhere(new PgBinary("<=", V("id"), V("lim")), orderById: true), Scroll: false) { Arguments = [new("lim", "integer")] },
                new PgDeclareCursor("sc", QtyWhere(PgLiteral.True, orderById: true), Scroll: true),
                new PgDeclare("rc", "refcursor"),
                new PgDeclare("r", "record"),
            ],
        };
        var exercise = new PgCreateRoutine(new PgName("plpg", "exercise"), false, [new PgParameter("n", "integer")],
            new PgPlBody(body) { Directives = ["#variable_conflict use_column"] })
        {
            Returns = "integer",
            Volatility = "VOLATILE",
        };

        await using var db = await PostgresDatabase.CreateAsync("plpgsql");
        await using var conn = await OpenAsync(db, exercise);
        Assert.That(await ScalarAsync(conn, "SELECT plpg.exercise(3)"), Is.EqualTo(484));
        Assert.That(await ScalarAsync(conn, "SELECT note FROM plpg.item WHERE id = 1"), Is.EqualTo("a\nb"));
    }

    [Test]
    public async Task SetReturningFunctionUsesReturnQueryAndReturnNext()
    {
        var rows = new PgCreateRoutine(new PgName("plpg", "item_rows"), false, [new PgParameter("min_qty", "integer")],
            new PgPlBody(new PgBlock([
                new PgReturnQuery(new PgSelect
                {
                    Targets = [new PgTarget(V("id", "i")), new PgTarget(V("qty", "i"))],
                    From = [new PgTableRef(Item, "i")],
                    Where = new PgBinary(">=", V("qty", "i"), V("min_qty", "item_rows")),
                    OrderBy = [new PgSortKey(V("id", "i"))],
                }),
                new PgReturnQuery(null) { Execute = PgLiteral.String("SELECT $1, $2"), Using = [N(-1), N(-2)] },
                new PgAssign(V("id", "item_rows"), N(-3)),
                new PgAssign(V("qty", "item_rows"), N(-4)),
                new PgReturnNext(),
                new PgReturn(),
            ]))
            { Directives = ["#variable_conflict use_column"] })
        {
            ReturnsTable = [new("id", "integer"), new("qty", "integer")],
            Volatility = "STABLE",
        };

        await using var db = await PostgresDatabase.CreateAsync("plpgsql");
        await using var conn = await OpenAsync(db, rows);
        var result = await BothEngines.RunPostgresAsync("SELECT id, qty FROM plpg.item_rows(40)", connectionString: db.ConnectionString);
        Assert.That(result.Rows.Select(r => string.Join(",", r)), Is.EqualTo(new[] { "4,40", "5,50", "-1,-2", "-3,-4" }));
    }

    [Test]
    public async Task ProceduresCommitAndCallWithNamedInoutArguments()
    {
        var addItem = new PgCreateRoutine(new PgName("plpg", "add_item"), true,
            [new PgParameter("qty", "integer"), new PgParameter("new_id", "integer", "INOUT", PgLiteral.Null)],
            new PgPlBody(new PgBlock([
                new PgSqlStatement(new PgInsert(Item, ["qty"], new PgValues([[V("qty", "add_item")]])) { Returning = [new PgTarget(V("id"))] })
                {
                    Into = [V("new_id", "add_item")],
                },
                new PgTransactionControl(true),
            ])));
        var caller = new PgCreateRoutine(new PgName("plpg", "caller"), true, [new PgParameter("result", "integer", "INOUT", PgLiteral.Null)],
            new PgPlBody(new PgBlock([
                new PgCall(new PgName("plpg", "add_item"), [new(V("v_id"), "new_id"), new(N(70), "qty")]),
                new PgAssign(V("result", "caller"), V("v_id")),
            ])
            {
                Declarations = [new PgDeclare("v_id", "integer")],
            }));

        await using var db = await PostgresDatabase.CreateAsync("plpgsql");
        await using var conn = await OpenAsync(db, addItem, caller);
        Assert.That(await ScalarAsync(conn, "CALL plpg.caller()"), Is.EqualTo(6));
        Assert.That(await ScalarAsync(conn, "SELECT qty FROM plpg.item WHERE id = 6"), Is.EqualTo(70));
    }

    [Test]
    public async Task SqlLanguageFunctionsAndDollarTags()
    {
        var add1 = new PgCreateRoutine(new PgName("plpg", "add1"), false, [new PgParameter("x", "integer")], new PgSqlReturnBody(Add(V("x"), N(1))))
        {
            Returns = "integer",
            Volatility = "IMMUTABLE",
        };
        var big = new PgCreateRoutine(new PgName("plpg", "big"), false, [new PgParameter("min_qty", "integer")],
            new PgSqlBody([new PgQueryStatement(new PgSelect
            {
                Targets = [new PgTarget(V("id"))],
                From = [new PgTableRef(Item)],
                Where = new PgBinary(">=", V("qty"), V("min_qty")),
            })]))
        {
            ReturnsTable = [new("id", "integer")],
            Volatility = "STABLE",
        };
        var price = new PgCreateRoutine(new PgName("plpg", "price"), false, [],
            new PgPlBody(new PgBlock([new PgReturn(PgLiteral.String("costs $$5 or $body$"))])))
        {
            Returns = "text",
        };

        await using var db = await PostgresDatabase.CreateAsync("plpgsql");
        await using var conn = await OpenAsync(db, add1, big, price);
        Assert.That(await ScalarAsync(conn, "SELECT plpg.add1(41)"), Is.EqualTo(42));
        Assert.That(await ScalarAsync(conn, "SELECT count(*)::integer FROM plpg.big(30)"), Is.EqualTo(3));
        Assert.That(await ScalarAsync(conn, "SELECT plpg.price()"), Is.EqualTo("costs $$5 or $body$"));
    }
}
